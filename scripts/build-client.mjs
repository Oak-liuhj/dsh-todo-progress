/** 将模块化客户端打成 DSH ModuleLoader 支持的单文件，不把 React 打进插件。 */
import {build} from 'esbuild';
import {readFile, writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const pkg = JSON.parse(await readFile(new URL('../package.json', import.meta.url), 'utf8'));
const result = await build({
    absWorkingDir: root, entryPoints: ['src/client/index.js'], bundle: true,
    format: 'cjs', platform: 'browser', target: 'es2020', external: ['react'],
    write: false, charset: 'utf8', legalComments: 'none',
    define: {__PLUGIN_VERSION__: JSON.stringify(pkg.version)},
    banner: {js: '// Generated by npm run build. Edit src/client/, not this file.\n' +
        'window.__ModuleLoader__.load({id: "dsh-todo-progress", factory: function(require) {\nvar module = {exports: {}}; var exports = module.exports;'},
    footer: {js: '\nreturn module.exports;\n}});'},
});
const target = new URL('../client.js', import.meta.url);
const output = result.outputFiles[0].text;
if (process.argv.includes('--check')) {
    if (await readFile(target, 'utf8') !== output) throw new Error('client.js is stale; run npm run build');
    console.log('Client artifact matches sources.');
} else {
    await writeFile(target, output);
    console.log(`Built client.js for ${pkg.name}@${pkg.version}`);
}
